CREATE TABLE IF NOT EXISTS Tours (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 category_id BIGINT NULL,
 title VARCHAR(200) NOT NULL,
 destination VARCHAR(200) NOT NULL,
 description TEXT NOT NULL,
 starts_at DATETIME NOT NULL,
 ends_at DATETIME NOT NULL,
 price BIGINT NOT NULL DEFAULT 0,
 capacity INT NOT NULL,
 publication VARCHAR(16) NOT NULL DEFAULT 'draft',
 version INT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_tour_catalogue(publication, starts_at),
 FOREIGN KEY(category_id) REFERENCES Topics(id) ON DELETE RESTRICT,
 CHECK(price >= 0), CHECK(capacity > 0), CHECK(ends_at > starts_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS Bookings (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT NULL,
 tour_id BIGINT NOT NULL,
 quantity INT NOT NULL,
 unit_price BIGINT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'pending',
 request_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 version INT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_user_tour(user_id,tour_id),
 INDEX idx_bookings_tour_status(tour_id,status),
 FOREIGN KEY(user_id) REFERENCES Data(UserId) ON DELETE SET NULL,
 FOREIGN KEY(tour_id) REFERENCES Tours(id) ON DELETE RESTRICT,
 CHECK(quantity BETWEEN 1 AND 20), CHECK(unit_price >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS BookingParticipants (
 booking_id BIGINT NOT NULL,
 ordinal INT NOT NULL,
 display_name VARCHAR(150) NULL,
 PRIMARY KEY(booking_id,ordinal),
 FOREIGN KEY(booking_id) REFERENCES Bookings(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS BookingStatusHistory (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 booking_id BIGINT NOT NULL,
 actor_id BIGINT NULL,
 old_status VARCHAR(16) NULL,
 new_status VARCHAR(16) NOT NULL,
 reason VARCHAR(500) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(booking_id) REFERENCES Bookings(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS Payments (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 booking_id BIGINT NOT NULL UNIQUE,
 amount BIGINT NOT NULL,
 method VARCHAR(16) NOT NULL,
 status VARCHAR(16) NOT NULL,
 order_ref CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 provider_tx VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL UNIQUE,
 expires_at DATETIME NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(booking_id) REFERENCES Bookings(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS AdminRoles (
 user_id BIGINT NOT NULL PRIMARY KEY,
 role VARCHAR(16) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS AuditLog (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 actor_id BIGINT NULL,
 action VARCHAR(64) NOT NULL,
 target_type VARCHAR(32) NOT NULL,
 target_id BIGINT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_audit_created(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS NotificationOutbox (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 chat_id BIGINT NOT NULL,
 method VARCHAR(32) NOT NULL,
 payload MEDIUMTEXT NOT NULL,
 idem_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 status VARCHAR(16) NOT NULL DEFAULT 'pending',
 attempts INT NOT NULL DEFAULT 0,
 available_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 locked_at DATETIME NULL,
 error_code VARCHAR(40) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 sent_at DATETIME NULL,
 INDEX idx_outbox_dispatch(status,available_at,id),
 INDEX idx_outbox_chat(chat_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS UpdateReceipts (
 update_id BIGINT NOT NULL PRIMARY KEY,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS RateLimits (
 user_id BIGINT NOT NULL,
 minute_slot BIGINT NOT NULL,
 hits INT NOT NULL,
 PRIMARY KEY(user_id,minute_slot)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS BotSessions (
 user_id BIGINT NOT NULL PRIMARY KEY,
 state VARCHAR(40) NOT NULL,
 payload TEXT NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES Data(UserId) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
